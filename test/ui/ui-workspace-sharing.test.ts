import assert from "node:assert/strict";
import test from "node:test";
import { api, signIn } from "../dev-nodes.js";
import { nativeUiFixture } from "./native-ui-fixture.js";

test("workspace creation chooses sharing recipients and existing rows can revoke them", { timeout: 120_000 }, async t => {
  const { page, environment, node } = await nativeUiFixture(t);
  const session = await signIn(environment, node);
  const createdCluster = await api<{ snapshot: { body: { clusterId: string } } }>(node, session, "POST", "/clusters", { name: "Client team" });
  assert.equal(createdCluster.status, 201);
  const clusterId = createdCluster.body.snapshot.body.clusterId;
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto(node.url, { waitUntil: "domcontentloaded" });
  await page.getByTestId("login-username-input").fill(environment.username);
  await page.getByTestId("login-password-input").fill(environment.password);
  await page.getByTestId("login-submit-button").click();
  await page.getByText("Internal Assistant", { exact: true }).waitFor();
  await page.getByTestId("settings-open-button").click();
  await page.getByTestId("settings-tab-workspaces").click();
  await page.waitForFunction(() => !(document.getElementById("settingsPanel-workspaces") as HTMLElement).inert);
  await page.getByTestId("workspace-name-input").fill("Shared clients");
  assert.equal(await page.getByTestId("workspace-name-input").inputValue(), "Shared clients");
  await page.getByTestId("workspace-create-sharing").click();
  assert.equal(await page.getByTestId("workspace-name-input").inputValue(), "Shared clients", "opening sharing preserves name");
  await page.getByTestId(`workspace-share-cluster-${clusterId}`).check();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  const bounds = await page.getByTestId("workspace-sharing-dialog").evaluate(element => {
    const rect = element.getBoundingClientRect();
    return { left: rect.left, right: rect.right, overflow: element.scrollWidth > element.clientWidth };
  });
  assert.ok(bounds.left >= 0 && bounds.right <= 390, JSON.stringify(bounds));
  assert.equal(bounds.overflow, false, "sharing controls fit a phone viewport");
  await page.setViewportSize({ width: 1440, height: 900 });
  assert.equal(await page.getByTestId("workspace-name-input").inputValue(), "Shared clients", "selection preserves name");
  await page.getByTestId("workspace-sharing-save").click();
  assert.equal(await page.getByTestId("workspace-name-input").inputValue(), "Shared clients", "choosing recipients must preserve the workspace name");
  const creationResponse = page.waitForResponse(response => response.url().endsWith("/api/workspaces") && response.request().method() === "PUT");
  await page.getByTestId("workspace-add-button").click();
  const response = await creationResponse;
  assert.equal(response.status(), 200, await response.text());
  const row = page.getByTestId("workspace-row").filter({ hasText: "Shared clients" });
  await row.waitFor();
  const sharing = await api<{ clusterIds: string[] }>(node, session, "GET", "/workspaces/shared-clients/sharing");
  assert.deepEqual(sharing.body.clusterIds, [clusterId]);
  await row.getByTestId("workspace-share-button").click();
  assert.equal(await page.getByTestId(`workspace-share-cluster-${clusterId}`).isChecked(), true);
  await page.getByTestId(`workspace-share-cluster-${clusterId}`).uncheck();
  await page.getByTestId("workspace-sharing-save").click();
  await page.getByTestId("workspace-sharing-dialog").waitFor({ state: "hidden" });
  assert.deepEqual((await api<{ clusterIds: string[] }>(node, session, "GET", "/workspaces/shared-clients/sharing")).body.clusterIds, []);
  assert.deepEqual(errors, []);
});
