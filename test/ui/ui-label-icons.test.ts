import assert from "node:assert/strict";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { type Browser } from "playwright-core";
import { launchChrome } from "./launch-chrome.js";
import type { SessionSummary } from "../../src/types.js";
import { api, seedDevEnvironment, signIn, startDevNode, stopDevNode } from "../dev-nodes.js";

test("labels show as icons, can be typed, cleared, or generated by an agent", { timeout: 120_000 }, async () => {
  const root = await mkdtemp(path.join(os.tmpdir(), "joint-bob-label-icons-ui-"));
  const generator = path.join(root, "generator.mjs");
  await writeFile(generator, 'export default async () => "🛟";\n');
  const environment = await seedDevEnvironment(root, 1);
  const node = environment.nodes[0];
  const server = await startDevNode(environment, node, { JOINT_BOB_LABEL_ICON_GENERATOR: generator });
  let browser: Browser | undefined;
  try {
    const auth = await signIn(environment, node);
    const project = node.projects.find((entry) => entry.name === "Internal Assistant")!;
    const sessions = (await api<{ sessions: SessionSummary[] }>(node, auth, "GET", `/projects/${project.id}/sessions`)).body.sessions;
    for (const [session, classification] of [[sessions[0], "Research"], [sessions[1], "Bug"], [sessions[2], "Support"]] as const) {
      assert.equal((await api(node, auth, "PUT", `/projects/${project.id}/sessions/classification`, { sessionId: session.id, engine: session.harnessId, classification })).status, 200);
    }
    browser = await launchChrome({ headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, serviceWorkers: "block" });
    const errors: string[] = [];
    page.on("pageerror", (error) => errors.push(error.message));
    await page.goto(node.url);
    await page.getByTestId("login-username-input").fill(environment.username);
    await page.getByTestId("login-password-input").fill(environment.password);
    await page.getByTestId("login-submit-button").click();
    await page.locator(".project-card", { hasText: project.name }).first().click();
    const badges = page.locator("#sessionList").getByTestId("session-classification");
    await badges.first().waitFor();
    assert.deepEqual((await badges.allTextContents()).sort(), ["Support", "🐞", "🔬"]);
    assert.equal(await page.locator('#sessionList [aria-label="Research"]').count(), 1, "an icon keeps its label for assistive tech");
    // The icon follows the title's text inside the title's own box, never on a row beneath it.
    const placed = await badges.first().evaluate(`(() => { const el = document.querySelector('#sessionList [data-testid="session-classification"]'); const title = el.closest('strong').getBoundingClientRect(); const box = el.getBoundingClientRect(); return { inline: getComputedStyle(el).display === "inline-block", insideTitle: box.top >= title.top && box.bottom <= title.bottom + 1 }; })()`) as { inline: boolean; insideTitle: boolean };
    assert.equal(placed.inline, true, "the label icon is an inline badge");
    assert.equal(placed.insideTitle, true, "the label icon sits within the title's text block");
  } finally {
    await browser?.close();
    await stopDevNode(server);
    await rm(root, { recursive: true, force: true });
  }
});
