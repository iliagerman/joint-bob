import assert from "node:assert/strict";
import test from "node:test";
import { nativeUiFixture } from "./native-ui-fixture.js";
import { api, signIn } from "../dev-nodes.js";

test("schedule profile picker defaults to current profile and restores explicit assignment", { timeout: 120_000 }, async t => {
  const { page, environment, node } = await nativeUiFixture(t);
  const auth = await signIn(environment, node);
  const created = await api<{ profile: { id: string } }>(node, auth, "POST", "/provider-profiles", { label: "Synthetic automation", provider: "claude" });
  assert.equal(created.status, 201);
  await page.goto(node.url);
  await page.locator('#loginDialog[open]').waitFor();
  await page.locator('#loginUsernameInput').fill(environment.username);
  await page.locator('#loginPasswordInput').fill(environment.password);
  await page.locator('#loginSubmitButton').click();
  await page.locator('[aria-label="Actions for Internal Assistant"]').click();
  await page.getByTestId('project-cron-button').click();
  await page.waitForFunction(() => document.querySelector<HTMLFormElement>('#cronForm')!.elements.namedItem('ownerNodeId') instanceof HTMLSelectElement && (document.querySelector<HTMLFormElement>('#cronForm')!.elements.namedItem('ownerNodeId') as HTMLSelectElement).options.length > 0);
  await page.locator('#cronNew').click();
  const picker = page.getByTestId('cron-provider-profile');
  await page.waitForFunction(() => !(document.querySelector('[data-testid="cron-provider-profile"]') as HTMLSelectElement).disabled);
  assert.equal(await picker.inputValue(), '');
  assert.equal(await picker.locator('option').first().textContent(), 'Use my current profile');
  await picker.selectOption(created.body.profile.id);
  await page.locator('#cronForm [name="name"]').fill('Profile test');
  await page.locator('#cronForm [name="prompt"]').fill('Synthetic, never executed');
  await page.locator('#cronForm [name="enabled"]').uncheck();
  await page.locator('#cronForm').evaluate((form: HTMLFormElement) => form.requestSubmit());
  await page.getByTestId('cron-edit').click();
  await page.waitForFunction(() => !(document.querySelector('[data-testid="cron-provider-profile"]') as HTMLSelectElement).disabled);
  assert.equal(await picker.inputValue(), created.body.profile.id);
  await picker.selectOption('');
  await page.locator('#cronForm').evaluate((form: HTMLFormElement) => form.requestSubmit());
  await page.getByTestId('cron-edit').click();
  assert.equal(await picker.inputValue(), '');
  await page.locator('#cronCancel').click();
  await page.locator('#cronClose').click();
  await page.getByTestId('settings-open-button').click();
  await page.getByTestId('settings-tab-webhooks').click();
  await page.waitForFunction(() => (document.querySelector('#webhooksProject') as HTMLSelectElement).options.length > 0 && !(document.querySelector('#webhooksNew') as HTMLButtonElement).disabled);
  await page.getByTestId('webhooks-new-button').click();
  const webhookPicker = page.getByTestId('webhooks-provider-profile');
  await page.waitForFunction(() => !(document.querySelector('[data-testid="webhooks-provider-profile"]') as HTMLSelectElement).disabled);
  assert.equal(await webhookPicker.inputValue(), '');
  await webhookPicker.selectOption(created.body.profile.id);
  await page.getByTestId('webhooks-name-input').fill('Profile webhook');
  await page.getByTestId('webhooks-save-button').click();
  await page.getByTestId('webhooks-reveal').waitFor({ state: 'visible' });
  await page.getByTestId('webhooks-reveal-done-button').click();
  await page.getByTestId('webhooks-back-button').click();
  await page.getByTestId('webhooks-open-button').click();
  await page.waitForFunction(() => !(document.querySelector('[data-testid="webhooks-provider-profile"]') as HTMLSelectElement).disabled);
  assert.equal(await webhookPicker.inputValue(), created.body.profile.id);
  await webhookPicker.selectOption('');
  await page.getByTestId('webhooks-save-button').click();
  await page.getByTestId('webhooks-status').getByText('Saved.').waitFor();
  await page.getByTestId('webhooks-back-button').click();
  await page.getByTestId('webhooks-open-button').click();
  assert.equal(await webhookPicker.inputValue(), '');
});
