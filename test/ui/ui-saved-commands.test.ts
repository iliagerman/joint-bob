import assert from "node:assert/strict";
import test from "node:test";
import { nativeUiFixture } from "./native-ui-fixture.js";

test("saved commands paste into chat through a keyboard shortcut without sending", { timeout: 240_000 }, async (t) => {
  const { page, environment, node } = await nativeUiFixture(t, (root) => ({ JOINT_BOB_TEST_ENGINE_LOG: `${root}/engine.log` }));
  await page.goto(node.url);
  await page.locator("#loginDialog[open]").waitFor();
  await page.getByTestId("login-username-input").fill(environment.username);
  await page.getByTestId("login-password-input").fill(environment.password);
  await page.getByTestId("login-submit-button").click();
  await page.locator(".project-card", { hasText: "Internal Assistant" }).first().waitFor();
  await page.evaluate(async () => (await import("/app/settings.js")).openSettings("commands"));
  const instructions = page.getByTestId("saved-commands-instructions");
  assert.match(await instructions.innerText(), /Enter to paste.*Nothing is sent/);
  assert.match(await page.locator("#savedCommandsShortcutHelp").innerText(), /L/);
  assert.match(await page.locator("#canvasKeymapCommand-savedCommands").locator("..").innerText(), /Saved \/ custom commands.*Settings → Commands/);
  await page.evaluate(async () => {
    const { state } = await import("/app/state.js");
    const previous = state.canvasKeymap;
    state.canvasKeymap = { ...previous, commands: { ...previous.commands, savedCommands: null } };
    await (await import("/app/shortcut-settings.js")).fillShortcutSettings();
    state.canvasKeymap = previous;
  });
  assert.match(await page.locator("#savedCommandsShortcutHelp").innerText(), /assign a keyboard shortcut/);
  await page.evaluate(async () => (await import("/app/shortcut-settings.js")).fillShortcutSettings());
  assert.match(await page.locator("#savedCommandsShortcutHelp").innerText(), /L/);
  await page.getByTestId("add-saved-command").click();
  await page.locator("#savedCommandsList input").fill("Review changes");
  await page.locator("#savedCommandsList textarea").fill("Review my changes, do not send this yet.");
  await page.getByTestId("settings-save-button").click();
  await page.locator("#settingsDialog[open]").waitFor({ state: "hidden" });
  await page.locator(".project-card", { hasText: "Internal Assistant" }).first().click();
  await page.locator("#sessionList .session-card", { hasText: "Thread-Based Agent Builder" }).click();
  assert.equal(await page.getByTestId("saved-commands-button").innerText(), "");
  assert.equal(await page.getByTestId("saved-commands-button").getAttribute("aria-label"), "Custom commands");
  assert.equal(await page.getByTestId("saved-commands-button").locator("svg").count(), 1);
  assert.equal(await page.locator('.composer-row #savedCommandsButton + #sendButton').count(), 1, "Custom commands must sit immediately beside Send");
  await page.getByTestId("chat-message-input").fill("Old draft");
  await page.keyboard.press("Control+Alt+Shift+L");
  await page.getByTestId("saved-commands-dialog").waitFor({ state: "visible" });
  await page.getByTestId("saved-commands-search").fill("Review");
  await page.getByTestId("saved-commands-options").getByText("Review changes", { exact: true }).waitFor();
  const usedCommand = page.waitForResponse((response) => response.url().includes("/api/commands/") && response.url().endsWith("/use"));
  await page.getByTestId("saved-commands-search").press("Enter");
  const useResponse = await usedCommand;
  assert.equal(useResponse.status(), 200, await useResponse.text());
  await page.waitForFunction(() => (document.querySelector('#messageInput') as HTMLTextAreaElement)?.value === "Review my changes, do not send this yet.");
  assert.equal(await page.getByTestId("chat-message-input").inputValue(), "Review my changes, do not send this yet.");
  assert.equal(await page.getByTestId("saved-commands-dialog").evaluate((dialog) => (dialog as HTMLDialogElement).open), false);
  await page.reload();
  await page.locator(".project-card", { hasText: "Internal Assistant" }).first().click();
  await page.locator("#sessionList .session-card", { hasText: "Thread-Based Agent Builder" }).click();
  await page.getByTestId("chat-message-input").click();
  await page.keyboard.press("Control+Alt+Shift+L");
  await page.getByTestId("saved-commands-dialog").waitFor({ state: "visible" });
  await page.getByTestId("saved-commands-options").getByText("Review changes").waitFor();
  assert.equal(await page.getByTestId("saved-commands-options").getByText("Review changes").count(), 1);
  assert.equal(await page.locator("#savedCommandsTitle").innerText(), "Recently used commands");
  await page.getByTestId("saved-commands-search").press("Escape");
  await page.evaluate(async () => (await import("/app/settings.js")).openSettings("commands"));
  await page.getByTestId("saved-command-share").click();
  await page.getByTestId("command-share-dialog").waitFor();
  await page.getByTestId("command-share-projectIds").first().check();
  await page.getByTestId("command-share-save").click();
  await page.getByTestId("command-share-dialog").waitFor({ state: "detached" });
  await page.getByTestId("saved-command-share").click();
  await page.getByTestId("command-share-dialog").waitFor();
  assert.equal(await page.getByTestId("command-share-projectIds").first().isChecked(), true, "Project sharing must persist through the real backend");
  await page.getByTestId("command-share-cancel").click();
  await page.getByTestId("settings-cancel-button").click();
  await page.getByTestId("chat-message-input").fill("Keep my draft");
  await page.getByTestId("saved-commands-button").click();
  await page.getByTestId("saved-commands-add").click();
  await page.getByTestId("create-command-name").fill("Conversation command");
  await page.getByTestId("create-command-prompt").fill("Created right here, without sending.");
  await page.getByTestId("create-command-save").click();
  await page.getByTestId("create-command-dialog").waitFor({ state: "hidden" });
  await page.getByTestId("saved-commands-options").getByText("Conversation command", { exact: true }).waitFor();
  assert.equal(await page.getByTestId("chat-message-input").inputValue(), "Keep my draft");
  await page.getByTestId("saved-commands-close").click();
  await page.reload();
  await page.locator(".project-card", { hasText: "Internal Assistant" }).first().click();
  await page.locator("#sessionList .session-card", { hasText: "Thread-Based Agent Builder" }).click();
  await page.getByTestId("saved-commands-button").click();
  await page.getByTestId("saved-commands-search").fill("Conversation command");
  await page.getByTestId("saved-commands-options").getByText("Conversation command", { exact: true }).click();
  await page.waitForFunction(() => (document.querySelector('#messageInput') as HTMLTextAreaElement)?.value === "Created right here, without sending.");
});
