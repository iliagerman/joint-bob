import assert from "node:assert/strict";
import { mkdtemp, rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { seedDevEnvironment, startDevNode, stopDevNode } from "../dev-nodes.js";
import { launchChrome } from "./launch-chrome.js";

test("personal assistant opens from conversation and saves a link with its screenshot", { timeout: 180_000 }, async () => {
  const root = await mkdtemp(path.join(os.tmpdir(), "personal-assistant-ui-"));
  let server: Awaited<ReturnType<typeof startDevNode>> | undefined;
  let browser: Awaited<ReturnType<typeof launchChrome>> | undefined;
  try {
    const environment = await seedDevEnvironment(root, 1);
    server = await startDevNode(environment, environment.nodes[0]);
    browser = await launchChrome({ headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, serviceWorkers: "block" });
    await page.goto(environment.nodes[0].url);
    await page.getByTestId("login-username-input").fill(environment.username);
    await page.getByTestId("login-password-input").fill(environment.password);
    await page.getByTestId("login-submit-button").click();
    await page.locator(".project-card", { hasText: "Internal Assistant" }).first().click();
    await page.locator(".session-card", { hasText: "Thread-Based Agent Builder" }).first().click();
    await page.locator("body.view-chat #chatPanel").waitFor({ state: "visible" });
    await page.waitForFunction(() => !(document.querySelector("#messageInput") as HTMLTextAreaElement).disabled);
    const button = page.getByTestId("chat-personal-assistant-button");
    assert.equal(await button.getAttribute("aria-label"), "Create assistant");
    assert.equal(await button.getAttribute("title"), "Create assistant");
    assert.equal(await button.isVisible(), true, "create assistant is visible in the desktop toolbar");
    assert.equal(await button.locator("svg.chat-toolbar-icon").count(), 1);
    assert.ok((await button.boundingBox())!.width <= 40, "assistant fits the icon toolbar");
    await page.setViewportSize({ width: 720, height: 844 });
    await page.getByTestId("chat-more-button").click();
    assert.equal(await button.getByText("Create assistant", { exact: true }).isVisible(), true, "mobile menu names the create action");
    await button.click();
    const dialog = page.getByTestId("personal-assistant-dialog");
    await dialog.waitFor({ state: "visible" });
    assert.equal(await dialog.locator(".dialog-card").evaluate(card => getComputedStyle(card).display), "flex", "name form uses the app dialog style");
    await dialog.getByTestId("personal-assistant-name").fill("Phone assistant");
    await dialog.getByTestId("personal-assistant-create").click();
    await page.locator("#heading").getByText("Phone assistant").waitFor();
    const id = new URL(page.url()).searchParams.get("id");
    assert.ok(id, "creation opens a permanent assistant URL");
    assert.equal(await page.locator("header a[href='/assistant.html']").count(), 1, "assistant list stays reachable");
    const shortcutUrl = await page.evaluate(async () => {
      const manifest = await (await fetch("/manifest.webmanifest")).json();
      return manifest.shortcuts.find((shortcut: { name: string }) => shortcut.name === "Personal assistants").url;
    });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(new URL(shortcutUrl, environment.nodes[0].url).href);
    await page.getByRole("button", { name: "Phone assistant", exact: true }).click();
    await page.locator("#chat-form").waitFor({ state: "visible" });
    assert.equal(await page.locator("#settings").isVisible(), false, "shortcut selection opens chat without exposing settings");
    assert.equal(await page.locator("#capture").isVisible(), false, "saved-item capture is separate from chat");
    await page.goBack();
    await page.locator("#chooser").waitFor({ state: "visible" });
    await page.goBack().catch(() => {});
    assert.equal(new URL(page.url()).pathname, "/assistant.html", "Back on the first screen stays on the page");
    await page.locator("#chooser").waitFor({ state: "visible" });
    await page.getByRole("button", { name: "Phone assistant", exact: true }).click();
    await page.locator("#chat-form").waitFor({ state: "visible" });
    await page.reload();
    await page.locator("#chat-form").waitFor({ state: "visible" });
    assert.equal(await page.locator("#settings").isVisible(), false, "direct assistant links reopen in chat");
    const assistantUrl = page.url();
    await page.getByTestId("assistant-new-scheduled-task").click();
    const automationDialog = page.getByTestId("assistant-automation-dialog");
    await automationDialog.waitFor({ state: "visible" });
    const automationFrame = page.frameLocator("#assistantAutomationFrame");
    // The frame boots the full workspace page; under load that takes longer than a normal dialog.
    await automationFrame.getByTestId("cron-dialog").waitFor({ state: "visible", timeout: 30_000 });
    assert.match(await automationFrame.locator("#cronContext").textContent() || "", /assistant/i);
    assert.equal(await automationFrame.locator(".shell").evaluate(element => getComputedStyle(element).display), "none", "assistant automation must not show the regular workspace");
    await automationFrame.getByTestId("cron-new").click();
    await automationFrame.getByTestId("cron-name").fill("Phone check-in");
    await automationFrame.getByTestId("cron-prompt").fill("Review the latest assistant topic");
    await automationFrame.getByTestId("cron-enabled").uncheck();
    await automationFrame.getByTestId("cron-save").click();
    await automationFrame.locator("#cronList").getByText("Phone check-in").waitFor();
    await automationFrame.getByTestId("cron-close").click();
    await automationDialog.waitFor({ state: "hidden" });
    assert.equal(page.url(), assistantUrl, "closing automation returns to the same assistant chat");
    await page.getByTestId("assistant-new-webhook").click();
    await automationDialog.waitFor({ state: "visible" });
    await automationFrame.getByTestId("webhooks-list-section").waitFor({ state: "visible", timeout: 10_000 });
    assert.equal(await automationFrame.locator(".shell").evaluate(element => getComputedStyle(element).display), "none", "assistant webhook management must not show the regular workspace");
    await automationFrame.getByTestId("webhooks-new-button").click();
    await automationFrame.getByTestId("webhooks-form").waitFor({ state: "visible" });
    assert.equal(await automationFrame.getByTestId("webhooks-target-kind-select").inputValue(), "assistant");
    await automationFrame.getByTestId("webhooks-tab-access").click();
    assert.equal(await automationFrame.getByTestId("webhooks-preserve-files-toggle").isVisible(), false, "an assistant's topics always keep their files");
    await automationFrame.getByTestId("webhooks-tab-setup").click();
    await automationFrame.getByTestId("webhooks-name-input").fill("Phone assistant webhook");
    await automationFrame.getByTestId("webhooks-save-button").click();
    await automationFrame.getByTestId("webhooks-reveal").waitFor({ state: "visible" });
    await automationFrame.getByTestId("webhooks-back-button").click();
    await automationFrame.locator("#webhooksList").getByText("Personal assistant", { exact: false }).waitFor();
    await automationFrame.getByTestId("settings-cancel-button").click();
    await automationDialog.waitFor({ state: "hidden" });
    assert.equal(page.url(), assistantUrl, "closing webhook management returns to the same assistant chat");
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.getByTestId("assistant-new-scheduled-task").click();
    await automationDialog.waitFor({ state: "visible" });
    await automationFrame.getByTestId("cron-dialog").waitFor({ state: "visible" });
    await automationFrame.getByTestId("cron-new").click();
    await automationFrame.getByTestId("cron-name").fill("Desktop check-in");
    await automationFrame.getByTestId("cron-prompt").fill("Review the latest assistant topic");
    await automationFrame.getByTestId("cron-enabled").uncheck();
    await automationFrame.getByTestId("cron-save").click();
    await automationFrame.locator("#cronList").getByText("Desktop check-in").waitFor();
    await automationFrame.getByTestId("cron-close").click();
    await automationDialog.waitFor({ state: "hidden" });
    await page.getByTestId("assistant-view-settings").click();
    await page.getByText("Decision model", { exact: true }).waitFor();
    await page.waitForFunction(() => (document.querySelector("#execution-harness") as HTMLSelectElement).options.length > 1);
    const harnessOptions = await page.locator("#execution-harness option").evaluateAll(options => options.filter(option => (option as HTMLOptionElement).value && !(option as HTMLOptionElement).disabled).map(option => (option as HTMLOptionElement).value));
    assert.ok(harnessOptions.length, "settings offer a ready execution agent");
    await page.locator("#execution-harness").selectOption(harnessOptions[0]);
    await page.waitForFunction(() => !(document.querySelector("#execution-model") as HTMLSelectElement).disabled && !(document.querySelector("#execution-effort") as HTMLSelectElement).disabled);
    const selectedHarness = await page.locator("#execution-harness").inputValue();
    const selectedModel = await page.locator("#execution-model").inputValue();
    const selectedEffort = await page.locator("#execution-effort").inputValue();
    await page.locator("#instructions").fill("Compare listings by price and warranty");
    await page.locator("#allow-terminal").uncheck();
    await page.locator("#settings button").click();
    await page.getByText("Settings saved").waitFor();
    await page.locator("#settings-view").waitFor({ state: "hidden" });
    assert.equal(await page.locator("#settings").isVisible(), false, "saving settings returns to chat");
    await page.getByTestId("assistant-view-resources").click();
    await page.locator("#allow-browser").waitFor({ state: "visible" });
    await page.locator("#allow-browser").uncheck();
    await page.locator(".res-bar", { hasText: "Browser use is off" }).waitFor();
    await page.getByTestId("assistant-view-saved-items").click();
    assert.equal(await page.locator("#collection").inputValue(), "Personal", "saved-item collections start with a neutral label");
    await page.locator("#title").fill("Phone A");
    await page.locator("#url").fill("https://example.test/phone-a");
    await page.locator("#images").setInputFiles({ name: "listing.png", mimeType: "image/png", buffer: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/9ZkAAAAASUVORK5CYII=", "base64") });
    await page.locator("#capture button").click();
    await page.getByText("Item saved").waitFor();
    const card = page.locator("#items article", { hasText: "Phone A" });
    await card.waitFor();
    assert.equal(await card.locator("a").getAttribute("href"), "https://example.test/phone-a");
    await card.locator("img").evaluate(image => (image as HTMLImageElement).decode());
    assert.equal(await card.locator("img").count(), 1);
    assert.ok(new URL(await page.locator("#chat").getAttribute("href") || "", environment.nodes[0].url).searchParams.get("sessionId"));
    await page.reload();
    await page.locator("#heading").getByText("Phone assistant").waitFor();
    await page.getByTestId("assistant-view-settings").click();
    assert.equal(await page.locator("#instructions").inputValue(), "Compare listings by price and warranty");
    assert.equal(await page.locator("#allow-terminal").isChecked(), false);
    await page.waitForFunction((expected) => {
      const harness = document.querySelector("#execution-harness") as HTMLSelectElement;
      const model = document.querySelector("#execution-model") as HTMLSelectElement;
      const effort = document.querySelector("#execution-effort") as HTMLSelectElement;
      return harness.value === expected.harness && model.value === expected.model && effort.value === expected.effort;
    }, { harness: selectedHarness, model: selectedModel, effort: selectedEffort });
    await page.getByTestId("assistant-view-resources").click();
    await page.locator("#allow-browser").waitFor({ state: "visible" });
    assert.equal(await page.locator("#allow-browser").isChecked(), false, "browser use is saved from Resources");
    await page.getByTestId("assistant-view-saved-items").click();
    await page.locator("#items article", { hasText: "Phone A" }).waitFor();
    await page.getByTestId("assistant-view-chat").click();
    await page.locator("#chat-form").waitFor({ state: "visible" });
    await page.getByTestId("assistant-view-settings").click();
    await page.locator("#chat").click();
    await page.locator("body.view-chat #chatPanel").waitFor({ state: "visible" });
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.getByTestId("chat-personal-assistant-button").click();
    await page.locator("#heading").getByText("Phone assistant").waitFor();
    assert.equal(new URL(page.url()).searchParams.get("id"), id, "conversation icon reopens the same assistant");
    await page.getByTestId("assistant-view-saved-items").click();
    let deleted = 0;
    page.on("request", request => { if (request.method() === "DELETE") deleted++; });
    const deletion = page.getByTestId("assistant-delete-dialog");
    await card.getByRole("button", { name: "Delete item", exact: true }).click();
    await deletion.waitFor({ state: "visible" });
    assert.equal(deleted, 0, "opening confirmation must not delete the item");
    await deletion.getByRole("button", { name: "Cancel", exact: true }).click();
    await deletion.waitFor({ state: "hidden" });
    assert.equal(deleted, 0, "cancel must preserve the item");
    assert.equal(await card.count(), 1);
    await card.getByRole("button", { name: "Delete item", exact: true }).click();
    await deletion.waitFor({ state: "visible" });
    await page.keyboard.press("Escape");
    await deletion.waitFor({ state: "hidden" });
    assert.equal(deleted, 0, "Escape must preserve the item");
    await card.getByRole("button", { name: "Delete item", exact: true }).click();
    await deletion.getByRole("button", { name: "Delete item", exact: true }).click();
    await card.waitFor({ state: "detached" });
    assert.equal(deleted, 1, "confirmation deletes exactly once");
    await page.reload();
    await page.getByText("Nothing saved yet.", { exact: true }).waitFor();
  } finally {
    await browser?.close();
    if (server) await stopDevNode(server);
    await rm(root, { recursive: true, force: true });
  }
});
