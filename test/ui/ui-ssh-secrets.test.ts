import assert from "node:assert/strict";
import { generateKeyPairSync } from "node:crypto";
import { mkdtemp, rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { type Browser } from "playwright-core";
import { launchChrome } from "./launch-chrome.js";
import { seedDevEnvironment, startDevNode, stopDevNode } from "../dev-nodes.js";

test("provider menu stays horizontal and SSH account saves and edits without exposing its key", { timeout: 240_000 }, async () => {
  const root = await mkdtemp(path.join(os.tmpdir(), "joint-bob-ssh-secrets-"));
  const environment = await seedDevEnvironment(root, 1);
  const node = environment.nodes[0];
  const server = await startDevNode(environment, node);
  let browser: Browser | undefined;
  try {
    browser = await launchChrome({ headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, serviceWorkers: "block" });
    await page.goto(node.url);
    await page.getByTestId("login-username-input").fill(environment.username);
    await page.getByTestId("login-password-input").fill(environment.password);
    await page.getByTestId("login-submit-button").click();
    await page.getByText("Internal Assistant", { exact: true }).waitFor();
    await page.getByTestId("settings-open-button").click();
    await page.getByTestId("settings-tab-secrets").click();
    await page.getByTestId("secret-account-add-button").click();
    const options = page.getByTestId("secret-account-provider-input-option");
    const geometry = await options.first().evaluate((item) => {
      const icon = item.querySelector("svg")!.getBoundingClientRect();
      const range = document.createRange(); range.selectNode(item.lastChild!); const text = range.getBoundingClientRect();
      return { iconRight: icon.right, textLeft: text.left, optionHeight: item.getBoundingClientRect().height };
    });
    assert.ok(geometry.textLeft >= geometry.iconRight, `icon must sit beside label: ${JSON.stringify(geometry)}`);
    assert.ok(geometry.optionHeight <= 48, `option should be compact: ${geometry.optionHeight}`);
    await page.getByTestId("secret-account-provider-input-search").fill("ssh");
    assert.deepEqual(await options.allTextContents(), ["SSH"]);
    await options.click();
    await page.getByTestId("secret-ssh-fields").waitFor();
    await page.getByTestId("secret-ssh-session-file").setInputFiles({ name: "session.mxtsessions", mimeType: "text/plain", buffer: Buffer.from("[Bookmarks]\nDemo=#109#0%192.0.2.10%3985%%%not-a-password-to-import") });
    await page.waitForFunction(() => (document.querySelector("#secretSshHost") as HTMLInputElement)?.value === "192.0.2.10");
    assert.equal(await page.getByTestId("secret-ssh-host").inputValue(), "192.0.2.10");
    assert.equal(await page.getByTestId("secret-ssh-port").inputValue(), "3985");
    assert.equal(await page.getByTestId("secret-ssh-username").inputValue(), "");
    assert.equal(await page.getByTestId("secret-ssh-password").inputValue(), "");
    await page.getByTestId("secret-account-label-input").fill("Test server");
    await page.getByTestId("secret-ssh-username").fill("deploy");
    await page.getByTestId("secret-ssh-expires-at").fill("2030-10-15");
    assert.match(await page.getByTestId("secret-ssh-upload").innerText(), /PEM/);
    const pem = generateKeyPairSync("rsa", { modulusLength: 2048 }).privateKey.export({ type: "pkcs1", format: "pem" }).toString();
    await page.getByTestId("secret-ssh-file").setInputFiles({ name: "id_rsa", mimeType: "text/plain", buffer: Buffer.from(pem) });
    assert.equal(await page.getByTestId("secret-ssh-key").inputValue(), pem);
    await page.getByTestId("secret-ssh-file").setInputFiles({ name: "server.pem", mimeType: "application/x-pem-file", buffer: Buffer.from(pem) });
    assert.equal(await page.getByTestId("secret-ssh-key").inputValue(), pem);
    const created = page.waitForResponse((response) => response.url().endsWith("/api/secrets/accounts") && response.request().method() === "POST");
    await page.getByTestId("secret-account-save-button").click();
    const response = await created;
    assert.equal(response.status(), 201);
    const body = await response.json() as { account: { variables: Array<{ name: string; kind: string; value?: string }> } };
    assert.deepEqual(body.account.variables.map(({ name, kind }) => [name, kind]), [["SSH_HOST", "value"], ["SSH_PORT", "value"], ["SSH_USERNAME", "value"], ["SSH_PRIVATE_KEY", "file"], ["SSH_EXPIRES_AT", "value"]]);
    assert.equal(JSON.stringify(body).includes("BEGIN RSA PRIVATE KEY"), false);
    await page.getByTestId("secret-account-dialog").waitFor({ state: "hidden" });
    await page.getByTestId("secret-account-list").getByText("Test server · SSH").waitFor();
    await page.getByTestId("secret-account-edit-button").first().click();
    assert.equal(await page.getByTestId("secret-ssh-key").inputValue(), "");
    await page.getByTestId("secret-ssh-password").fill("synthetic-password");
    await page.getByTestId("secret-ssh-remove-key").click();
    const updated =  page.waitForResponse((response) => response.url().includes("/api/secrets/accounts/") && response.request().method() === "PUT");
    await page.getByTestId("secret-account-save-button").click();
    const updatedResponse = await updated;
    assert.equal(updatedResponse.status(), 200);
    const edited = await updatedResponse.json() as { account: { variables: Array<{ name: string }> } };
    assert.deepEqual(edited.account.variables.map(({ name }) => name), ["SSH_HOST", "SSH_PORT", "SSH_USERNAME", "SSH_PASSWORD", "SSH_EXPIRES_AT"]);
  } finally {
    await browser?.close();
    await stopDevNode(server);
    await rm(root, { recursive: true, force: true });
  }
});
