import assert from "node:assert/strict";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";
import test from "node:test";
import { iconsForLabels, labelIconPrompt, parseGeneratedIcon } from "../src/conversation-labels.js";
import type { SettingsResponse } from "../src/settings.js";
import { api, seedDevEnvironment, signIn, startDevNode, stopDevNode } from "./dev-nodes.js";

test("generated icon replies reduce to the first emoji", () => {
  assert.equal(parseGeneratedIcon("🐞"), "🐞");
  assert.equal(parseGeneratedIcon("Sure! How about 🔬 for research"), "🔬");
  assert.equal(parseGeneratedIcon("👩‍💻"), "👩‍💻");
  assert.equal(parseGeneratedIcon("I would pick a magnifying glass"), undefined);
  assert.match(labelIconPrompt('Bug "x"'), /exactly one emoji/);
});

test("icons follow their labels and drop with them", () => {
  assert.deepEqual(iconsForLabels(["Bug", "Support"], { Bug: "🐞", Gone: "👻" }), { Bug: "🐞" });
});

test("saved icon maps gain new built-in icons without replacing custom icons", async () => {
  const root = await mkdtemp(path.join(os.tmpdir(), "joint-bob-legacy-label-icons-"));
  const environment = await seedDevEnvironment(root, 1);
  const node = environment.nodes[0];
  const db = new DatabaseSync(path.join(node.dataDir, "node.db"));
  try {
    // A saved map from before Deploy to prod and Hotfix were introduced.
    db.prepare("INSERT OR REPLACE INTO node_settings (key, value, is_secret, updated_at) VALUES (?, ?, 0, ?)")
      .run("conversationLabelIcons", JSON.stringify({ Research: "🔬", Bug: "🐛", Feature: "✨", POC: "🧪", Support: "🛟" }), new Date().toISOString());
  } finally {
    db.close();
  }
  const server = await startDevNode(environment, node);
  try {
    const auth = await signIn(environment, node);
    const settings = (await api<SettingsResponse>(node, auth, "GET", "/settings")).body;
    assert.deepEqual(settings.conversationLabelIcons, { Research: "🔬", Bug: "🐛", Feature: "✨", POC: "🧪", "Deploy to prod": "🚀", Hotfix: "🔥", Support: "🛟" });
  } finally {
    await stopDevNode(server);
    await rm(root, { recursive: true, force: true });
  }
});

test("label icons persist, validate, and can be generated by an agent", async () => {
  const root = await mkdtemp(path.join(os.tmpdir(), "joint-bob-label-icons-"));
  const generator = path.join(root, "generator.mjs");
  await writeFile(generator, 'export default async ({ label }) => label === "Nothing" ? "no idea" : `Here: 🛟 (${label})`;\n');
  const environment = await seedDevEnvironment(root, 1);
  const node = environment.nodes[0];
  let server = await startDevNode(environment, node, { JOINT_BOB_LABEL_ICON_GENERATOR: generator });
  try {
    const auth = await signIn(environment, node);
    const settings = (await api<SettingsResponse>(node, auth, "GET", "/settings")).body;
    assert.deepEqual(settings.conversationLabelIcons, { Research: "🔬", Bug: "🐞", Feature: "✨", POC: "🧪", "Deploy to prod": "🚀", Hotfix: "🔥" });
    const input = { ...settings, ...settings.runtimeOverrides, conversationLabels: ["Bug", "Support"], conversationLabelIcons: { Bug: "🐛", Support: "🛟", Removed: "👻" } };
    assert.equal((await api(node, auth, "PUT", "/settings", input)).status, 200);
    const saved = (await api<SettingsResponse>(node, auth, "GET", "/settings")).body;
    assert.deepEqual(saved.conversationLabelIcons, { Research: "🔬", Bug: "🐛", Feature: "✨", POC: "🧪", "Deploy to prod": "🚀", Hotfix: "🔥", Support: "🛟" });
    // A blank field omits the icon from the submitted map. Keep deliberate removals,
    // but do not mistake a label missing from an older list for an icon removal.
    const edited = { ...input, conversationLabels: saved.conversationLabels, conversationLabelIcons: { ...saved.conversationLabelIcons } };
    delete edited.conversationLabelIcons.Hotfix;
    delete edited.conversationLabelIcons.Bug;
    edited.conversationLabelIcons["Deploy to prod"] = "📦";
    assert.equal((await api(node, auth, "PUT", "/settings", edited)).status, 200);
    const icons = (await api<SettingsResponse>(node, auth, "GET", "/settings")).body.conversationLabelIcons;
    assert.deepEqual(icons, { Research: "🔬", Feature: "✨", POC: "🧪", "Deploy to prod": "📦", Support: "🛟" });
    const { conversationLabelIcons: _icons, ...labelsOnly } = edited;
    assert.equal((await api(node, auth, "PUT", "/settings", { ...labelsOnly, conversationLabels: ["Support"] })).status, 200);
    assert.deepEqual((await api<SettingsResponse>(node, auth, "GET", "/settings")).body.conversationLabelIcons, icons,
      "updating labels without an icon map preserves cleared and customized icons");
    for (const icons of [{ Bug: " " }, { Bug: "x".repeat(17) }, { Bug: 3 }]) {
      assert.equal((await api(node, auth, "PUT", "/settings", { ...input, conversationLabelIcons: icons })).status, 400);
    }
    const generated = await api<{ icon: string }>(node, auth, "POST", "/settings/label-icon", { label: "Docs" });
    assert.equal(generated.status, 200);
    assert.equal(generated.body.icon, "🛟");
    assert.equal((await api(node, auth, "POST", "/settings/label-icon", { label: "Nothing" })).status, 422);
    assert.equal((await api(node, auth, "POST", "/settings/label-icon", { label: "Docs", harnessId: "missing" })).status, 422);
    assert.equal((await api(node, auth, "POST", "/settings/label-icon", { label: " " })).status, 400);
    await stopDevNode(server);
    server = await startDevNode(environment, node);
    const reauth = await signIn(environment, node);
    assert.deepEqual((await api<SettingsResponse>(node, reauth, "GET", "/settings")).body.conversationLabelIcons, icons,
      "cleared and customized icons survive a server restart");
  } finally {
    await stopDevNode(server);
    await rm(root, { recursive: true, force: true });
  }
});
